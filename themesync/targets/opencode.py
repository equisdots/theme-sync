# ═══════════════════════════════════════════════════════════════════════════
# opencode — per-palette themes + active theme in tui.json.
#
# Generates ~/.config/opencode/themes/<slug>.json (V1 theme: base16 `defs` +
# structural colors derived from background/foreground) and sets the active
# palette's theme in tui.json (atomic, keeps the rest of the keys; created on
# a fresh profile because opencode only writes it when a TUI setting changes).
# Custom themes whose slug is not a palette are kept; one-time snapshot of
# pre-existing themes in themes.bak. When opencode v2's cli.json already
# exists its `theme` object is updated too (v2 migrates tui.json on first run).
# A running TUI re-reads this on its next start (or via its own settings).
# ═══════════════════════════════════════════════════════════════════════════
from __future__ import annotations

import json

from ..core import load_json, mix, palette_bg_fg

NAME = "opencode"
DESCRIPTION = "per-palette themes + active theme in tui.json"

OC_REL = ".config/opencode"
TUI_SCHEMA = "https://opencode.ai/tui.json"
# Manifest of slugs generated by us (the dir may hold user themes; only what we
# generated and is no longer a palette gets removed).
STATE_REL = ".local/state/quickshell/themesync/opencode-themes.json"


def available(env) -> bool:
    # The config dir may exist on a fresh profile before opencode has run; the
    # themes dir is created below. Requiring themes/ made the target skip
    # exactly the fresh installs it should populate.
    return (env.home / OC_REL).is_dir()


def apply(env) -> list:
    out = []
    root = env.home / OC_REL
    themes = root / "themes"
    env.copytree_once(themes, root / "themes.bak")
    env.mkdir(themes)

    # ── 1) Regenerate per-palette themes ──
    slugs = []
    for pal in env.palettes:
        slug = pal.get("slug") or "?"
        b = pal.get("base16") or {}
        bg, fg = palette_bg_fg(pal)

        def c(i, fallback=fg):
            return b.get("color%d" % i) or fallback

        defs = {
            "bg0": bg,
            "red": c(1), "green": c(2), "yellow": c(3), "orange": c(4),
            "purple": c(5), "cyan": c(6), "fg0": fg, "muted": c(8),
            "redBright": c(9, c(1)), "greenBright": c(10, c(2)),
            "yellowBright": c(11, c(3)), "orangeBright": c(12, c(4)),
            "purpleBright": c(13, c(5)), "cyanBright": c(14, c(6)),
            "fgBright": c(15, fg),
        }
        theme = {
            "primary": "cyan", "secondary": "purple", "accent": "cyan",
            "error": "red", "warning": "yellow", "success": "green", "info": "cyan",
            "text": "fg0", "textMuted": "muted", "background": "bg0",
            "backgroundPanel": mix(bg, fg, 0.06),
            "backgroundElement": mix(bg, fg, 0.12),
            "border": mix(bg, fg, 0.20),
            "borderActive": "cyan",
            "borderSubtle": mix(bg, fg, 0.10),
            "diffAdded": "green", "diffRemoved": "red", "diffContext": "fg0",
            "diffHunkHeader": "muted", "diffHighlightAdded": "green",
            "diffHighlightRemoved": "red",
            "diffAddedBg": mix(bg, c(2), 0.15),
            "diffRemovedBg": mix(bg, c(1), 0.15),
            "diffContextBg": "bg0", "diffLineNumber": "muted",
            "diffAddedLineNumberBg": mix(bg, c(2), 0.15),
            "diffRemovedLineNumberBg": mix(bg, c(1), 0.15),
            "markdownText": "fg0", "markdownHeading": "cyan", "markdownLink": "orange",
            "markdownLinkText": "cyan", "markdownCode": "green",
            "markdownBlockQuote": "muted", "markdownEmph": "yellow",
            "markdownStrong": "yellow", "markdownHorizontalRule": "muted",
            "markdownListItem": "cyan", "markdownListEnumeration": "cyan",
            "markdownImage": "orange", "markdownImageText": "cyan",
            "markdownCodeBlock": "fg0",
            "syntaxComment": "muted", "syntaxKeyword": "purple", "syntaxFunction": "cyan",
            "syntaxVariable": "orange", "syntaxString": "green", "syntaxNumber": "yellow",
            "syntaxType": "orange", "syntaxOperator": "red", "syntaxPunctuation": "fg0",
        }
        data = {"$schema": "https://opencode.ai/theme.json", "defs": defs, "theme": theme}
        env.write(themes / (slug + ".json"), json.dumps(data, indent=2) + "\n")
        slugs.append(slug)

    # ── 2) Orphan cleanup: only what we generated ──
    # The opencode themes directory may hold user themes, so (unlike
    # kitty/starship/Qt, whose directories are 100% ours) a manifest of the
    # generated slugs is kept and only slugs that are no longer a palette get
    # removed. Without a previous manifest nothing is deleted.
    state = env.home / STATE_REL
    previous = load_json(state, []) or []
    for slug in previous:
        if slug not in slugs:
            env.unlink(themes / (slug + ".json"))
    env.write(state, json.dumps(slugs, indent=2) + "\n")

    out.append("opencode themes regenerated from dock/palettes: %d" % len(slugs))

    # ── 3) Active theme in tui.json (keeps the rest) ──
    # opencode ≤1.19 reads the TUI config from tui.json (global: $XDG_CONFIG_HOME
    # or ~/.config/opencode). It only creates the file when a TUI setting changes,
    # so a fresh profile had no active theme at all: create it when missing.
    tui = root / "tui.json"
    data = load_json(tui, {}) if tui.is_file() else {}
    if not isinstance(data, dict):
        data = {}
    data.setdefault("$schema", TUI_SCHEMA)
    data["theme"] = env.slug
    env.write(tui, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    out.append("opencode theme → '%s' (tui.json)" % env.slug)

    # opencode v2 reads the TUI config from cli.json and stores the theme as
    # {"name": ..., "mode": ...}. It migrates tui.json once, but when cli.json
    # already exists (v2 profile) keep it in sync as well. Never create it here:
    # on ≤1.19 it would be ignored and only add noise.
    cli = root / "cli.json"
    if cli.is_file():
        cli_data = load_json(cli)
        if isinstance(cli_data, dict):
            theme = cli_data.get("theme")
            if isinstance(theme, dict):
                theme["name"] = env.slug
            else:
                cli_data["theme"] = {"name": env.slug}
            env.write(cli, json.dumps(cli_data, indent=2, ensure_ascii=False) + "\n")
            out.append("opencode theme → '%s' (cli.json)" % env.slug)
    return out
